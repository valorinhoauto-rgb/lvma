export function normalizeWord(raw: string): string {
  if (!raw) return '';
  return raw
    .trim()
    .toUpperCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '') // remove acentos
    .replace(/Ç/g, 'C')
    .replace(/[^A-Z]/g, ''); // remove hífens, espaços e pontuações
}

